def fmt(v, nd=2):
    return "nan" if v is None or (isinstance(v, float) and not np.isfinite(v)) else f"{v:.{nd}f}"


def ms(summary, cond, metric, nd=2):
    r = summary[(summary.condition == cond) & (summary.metric == metric)]
    if r.empty or not np.isfinite(r["mean"].iloc[0]):
        return "n/a"
    n = int(r["n"].iloc[0])
    if n < 2:
        return f"{r['mean'].iloc[0]:.{nd}f} (n={n})"
    return f"{r['mean'].iloc[0]:.{nd}f} ± {r['sd'].iloc[0]:.{nd}f}" + (f" (n={n})" if n < 10 else "")


def mean_of(summary, cond, metric):
    r = summary[(summary.condition == cond) & (summary.metric == metric)]
    return float(r["mean"].iloc[0]) if not r.empty else np.nan


def draw_panel(series_by_cond, path):
    colors = {"base": "#7f7f7f", "chat": "#1f77b4", "oversight": "#ff7f0e", "pressure": "#2ca02c", "pressure_oversight": "#d62728"}
    styles = {"base": ":", "chat": "-", "oversight": "-", "pressure": "--", "pressure_oversight": "--"}
    specs = [("trade_price", "Mean trade price ($)", "mean ± 1 sd over runs"),
             ("words", "Words per seller message", "mean ± 1 sd over runs"),
             ("price_share", "Share of messages naming a price", "mean ± 1 sd over runs"),
             ("ident", "Share of runs with 5 identical asks", "share ± 1 s.e. over runs")]
    rounds = np.arange(1, 31)
    fig, axes = plt.subplots(1, 4, figsize=(15, 3.9), dpi=300)
    for ax, (key, title, sub) in zip(axes, specs):
        for cond in ORDER:
            M = np.array([s[key] for s in series_by_cond[cond]])
            if M.size == 0 or np.all(np.isnan(M)):
                continue
            mean, sd = np.nanmean(M, axis=0), np.nanstd(M, axis=0, ddof=1)
            n = np.sum(np.isfinite(M), axis=0)
            band = sd / np.sqrt(np.maximum(n, 1)) if key == "ident" else sd
            ax.plot(rounds, mean, color=colors[cond], ls=styles[cond], lw=1.7, label=LABEL[cond])
            ax.fill_between(rounds, mean - band, mean + band, color=colors[cond], alpha=0.13, lw=0)
        if key == "trade_price":
            ax.axhline(CE, ls="--", c="k", lw=0.8)
            ax.axhline(JPM, ls="--", c="k", lw=0.8)
            ax.text(29.5, CE + 0.3, "competitive $90", ha="right", fontsize=7)
            ax.text(29.5, JPM + 0.3, "cartel $100", ha="right", fontsize=7)
        if key in ("price_share", "ident"):
            ax.set_ylim(-0.02, 1.02)
        if key == "words":
            ax.set_ylim(bottom=0)
        ax.set_title(f"{title}\n({sub})", fontsize=9.5)
        ax.set_xlabel("round", fontsize=9)
        ax.set_xlim(1, 30)
        ax.tick_params(labelsize=8)
        ax.grid(alpha=0.3)
    axes[0].legend(fontsize=7.5, loc="lower right", frameon=True)
