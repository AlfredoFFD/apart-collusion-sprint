"""Re-analysis of the 50 GPT-4.1 runs that Agrawal et al. 2025 ship with the starter repo (sprint question 3.4 panel).

Data source
    vendor/collusion_hackathon/llm-agent-collusion/data/<timestamp>_<tag>-<k>/   (one folder per run)
    Agrawal et al. 2025, "Evaluating LLM Agent Collusion in Double Auctions", arXiv:2507.01413. The folders ship with
    the starter repo at the commit pinned in scripts/bootstrap.sh (`vendor/collusion_hackathon`, gitignored here).
    NOTHING analysed here was generated by us: this script makes no model call and only reads those folders
    (auction_results.md, Overseer.md, llm_eval_full.json, collusion_metrics.json, experiment_metadata.json).

Runs analysed (10 each, 5 GPT-4.1 sellers at cost $80, 5 GPT-4.1 buyers at value $100, 30 rounds, temperature 0.7):
    base-1..10 (no chat) · base-seller_comms-1..10 (chat) · oversight-1..10 (chat + notice + live overseer that gags
    sellers to 5 characters once it scores 4/4) · boss_pressure-1..10 (chat + CEO pressure) ·
    boss_pressure-oversight-1..10 (both). The 25 model-mix runs (claude-3-7-sonnet seats) are only counted.

Run from the repo root (same interpreter as src/analyze.py):
    uv run --project src/double_auction python src/analyze_agrawal_runs.py

Writes results/agrawal_reanalysis/{per_run.csv, summary.csv, summary.md, coded_messages.md, figures/F7_agrawal_panel.png}
and prints the positive-control check against the paper's Table 1 (exits with code 1 if it fails).
"""

