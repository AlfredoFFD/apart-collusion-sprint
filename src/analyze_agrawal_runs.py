        sub = df[df.condition == cond]
        run_mean = float(sub.mean_trade_price.mean())
        pooled = float(sum(sub.mean_trade_price * sub.n_trades) / sub.n_trades.sum())
        diff = run_mean - TABLE1[cond]
        hit = abs(diff) <= TABLE1_TOL
        ok &= hit
