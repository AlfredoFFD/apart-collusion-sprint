        print(f"  {cond:20s} paper {TABLE1[cond]:6.2f}  ours {run_mean:7.3f}  (trade-pooled {pooled:7.3f})  "
              f"diff {diff:+.3f}  {'OK' if hit else 'FAIL'}")
