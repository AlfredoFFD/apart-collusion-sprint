"""Build the themed edition of the paper (report/paper/paper_themed.tex) from the NeurIPS edition (paper.tex).

The themed edition is set in PP Neue Montreal with the website's title band and palette (preamble_themed.tex);
its abstract and body are taken from paper.tex, so the two editions always carry the same text.

  python scripts/paper_themed.py && cd report/paper && latexmk -lualatex paper_themed.tex
"""
from __future__ import annotations

import re
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1] / "report" / "paper"

HEADER = r"""\documentclass[10pt]{article}
\input{preamble_themed}
\input{generated/numbers}
\input{generated/probe}
\input{generated/market2}

% generated by scripts/paper_themed.py from paper.tex; edit paper.tex, not this file

\begin{document}

% =========================================================================================================
% Title band: the website hero, set on the page
% =========================================================================================================
\thispagestyle{empty}
\begin{tikzpicture}[remember picture, overlay]
  \def\bandh{3.55in}
  \def\colw{3.09in}
  \fill[black] (current page.north west) rectangle ([xshift=\colw, yshift=-\bandh]current page.north west);
  \begin{scope}
    \clip (current page.north west) rectangle ([xshift=\colw, yshift=-\bandh]current page.north west);
    \node[anchor=south, inner sep=0] at ([xshift=0.5*\colw, yshift=-\bandh]current page.north west)
      {\includegraphics[width=\colw]{figs/godfather.png}};
  \end{scope}
  \fill[brand] ([xshift=\colw]current page.north west) rectangle ([yshift=-\bandh]current page.north east);
  \node[anchor=north west, text=white, font=\fontsize{9}{11}\selectfont\bfseries]
    at ([xshift=0.32in, yshift=-0.3in]current page.north west) {Team P1};
  \node[anchor=north east, text=white, font=\fontsize{8}{10}\selectfont, align=right]
    at ([xshift=-0.4in, yshift=-0.3in]current page.north east)
    {Apart Research \quad AI Collusion Research Sprint \quad October 2026};
  \node[anchor=north west, text=white, inner sep=0, font=\fontsize{66}{60}\selectfont\bfseries]
    at ([xshift=\colw+0.55in, yshift=-1.05in]current page.north west) {GRAFT++};
  \node[anchor=north west, text=white, inner sep=0, align=left, font=\fontsize{8.4}{11}\selectfont]
    at ([xshift=\colw+0.6in, yshift=-2.03in]current page.north west)
    {Jayden Jeong*, Alfredo Frontera*, Jake Li*, Rohan Dash\\[-1pt]
     {\color{brandsoft}\itshape\fontsize{6.6}{8}\selectfont * equal contribution}};
  \node[anchor=south west, text=brandsoft, inner sep=0, align=left, text width=3.15in,
    font=\fontsize{13.5}{15.5}\selectfont\bfseries]
    at ([xshift=\colw+0.6in, yshift=-\bandh+0.32in]current page.north west)
    {Reducing Collusive Behavior in Agents via Localized Training and J-space Monitoring};
\end{tikzpicture}
\vspace*{2.75in}

{\editorialthin\fontsize{24}{27}\selectfont What does an AI cartel do when it learns it is being watched?\par}
\vspace{0.6em}

\begin{minipage}{\linewidth}
\fontsize{8.6}{11.7}\selectfont
\textbf{Abstract.}\enspace
%ABSTRACT%
\end{minipage}

\vspace{0.8em}
\begin{numbers}
\bignum{\DuoUnw}{collusion index of untrained, unwatched duopolies (100 rounds; 1 = monopoly)}\hfill
\bignum{\DuoWat}{the same pairs, told a compliance team reads the channel}\hfill
\bignum{\MtGptAll}{of GPT-4.1 sellers' messages still coordinate once all are fined; their prices did not move}\hfill
\bignum{%REL%}{less collusion with \graftpp\ than GRAFT when the monitor cannot see it}
\end{numbers}

\newpage
"""


def main() -> None:
    src = (PAPER / "paper.tex").read_text()
    abstract = re.search(r"\\begin\{abstract\}\s*(.*?)\s*\\end\{abstract\}", src, re.S).group(1)
    body = src[src.index("% =====", src.index(r"\end{abstract}")):]
    numbers = (PAPER / "generated" / "numbers.tex").read_text()
    rel = re.search(r"removes about (\d+)\\%", numbers).group(1) + r"\%"
    # the wider themed page fits the reasoning-card figure at the top of a page; long paths may break loosely
    body = body.replace(r"\begin{figure}[p]", r"\begin{figure}[tp]")
    body = body.replace(r"\section{Reproducibility}", r"\section{Reproducibility}\sloppy")
    out = HEADER.replace("%ABSTRACT%", abstract).replace("%REL%", rel) + body
    (PAPER / "paper_themed.tex").write_text(out)
    print(f"wrote {PAPER / 'paper_themed.tex'} ({len(out):,} chars)")


if __name__ == "__main__":
    main()
